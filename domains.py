def classify_domain_by_keywords(text: str) -> str | None:
    """按关键词规则给题目文本打知识域标签，无法判断返回 None。"""
    best_domain, best_hits = None, 0
    for domain, keywords in DOMAIN_KEYWORDS:
        hits = sum(1 for kw in keywords if kw.lower() in text.lower())
        if hits > best_hits:
            best_domain, best_hits = domain, hits
    return best_domain if best_hits > 0 else None


def normalize_for_match(text: str) -> str:
    """题干前缀比对用的归一化：去空白/全半角标点差异。"""
    return re.sub(r"[\s，。：:；;、（）()\.,．]", "", text)
